#!/usr/bin/env node
/**
 * REGENERATE THE PROCUREMENT REGISTER FROM THE ACT INFRASTRUCTURE PROJECT.
 *
 * `goods_procurement_entities` lives in the ACT infrastructure Supabase, not in Goods, and it is
 * not an organisation register however much it looks like one. It is an entity x community
 * cross-join: 4,562 rows carrying 1,049 distinct ABNs. Northern Land Council is in there 338
 * times, once per community, each row repeating the same $7.1M of contracts. Anything summed off
 * it is inflated about nine-fold — the raw table totals $17.07bn of government contracts where
 * the deduped truth is $1.87bn.
 *
 * That shape is why the same question has produced a different answer every time it was asked,
 * and why "Palm Island's buyers are Cooktown orgs": reading one slice of a cross-join returns
 * geographic nonsense, not a bug you can fix in the query.
 *
 * So this script dedupes by ABN at the source and writes a typed module into the Goods repo.
 * Goods then reads a file that cannot inflate, instead of a table that always will. It keeps only
 * entities that are community-controlled or hold at least one government contract, because an
 * entity that is neither is not a procurement pathway — that is 144 of the 1,049.
 *
 *   node scripts/generate-procurement-register.mjs         # writes src/lib/data/procurement-register.ts
 *
 * Needs ACT_INFRA_SUPABASE_URL and ACT_INFRA_SUPABASE_KEY. Read-only against ACT's database:
 * this never writes to a project Goods does not own.
 */

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const AU = process.env.ACT_INFRA_SUPABASE_URL;
const AK = process.env.ACT_INFRA_SUPABASE_KEY;
if (!AU || !AK) {
  console.error('Missing ACT_INFRA_SUPABASE_URL / ACT_INFRA_SUPABASE_KEY.');
  process.exit(2);
}

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../src/lib/data/procurement-register.ts');
const FIELDS = [
  'entity_name', 'abn', 'gs_id', 'entity_type', 'buyer_role', 'is_community_controlled',
  'govt_contract_count', 'govt_contract_value', 'estimated_annual_spend', 'procurement_method', 'website',
].join(',');

const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");

async function main() {
  /** Everything that could be a pathway: community-controlled, or holding a contract. */
  const filter = 'or=(is_community_controlled.eq.true,govt_contract_count.gt.0)';
  const rows = [];
  for (let offset = 0; ; offset += 1000) {
    const res = await fetch(`${AU}/rest/v1/goods_procurement_entities?select=${FIELDS}&${filter}&limit=1000&offset=${offset}`, {
      headers: { apikey: AK, Authorization: `Bearer ${AK}` },
    });
    if (!res.ok) { console.error(`HTTP ${res.status}`); process.exit(2); }
    const page = await res.json();
    rows.push(...page);
    if (page.length < 1000) break;
  }

  // Dedupe by ABN. The duplicate rows are identical except for community_id, which points into
  // ACT's communities table and resolves to none of the 34 Goods communities — so it carries no
  // information we can use and is dropped rather than picked arbitrarily.
  const byAbn = new Map();
  for (const r of rows) {
    const key = r.abn || r.entity_name;
    if (!byAbn.has(key)) byAbn.set(key, r);
  }
  const entities = [...byAbn.values()].sort(
    (a, b) => (b.govt_contract_value ?? 0) - (a.govt_contract_value ?? 0) || a.entity_name.localeCompare(b.entity_name),
  );

  const communityControlled = entities.filter((e) => e.is_community_controlled).length;
  const withContracts = entities.filter((e) => (e.govt_contract_count ?? 0) > 0).length;
  const both = entities.filter((e) => e.is_community_controlled && (e.govt_contract_count ?? 0) > 0).length;
  const totalValue = entities.reduce((n, e) => n + (e.govt_contract_value ?? 0), 0);

  const body = `// GENERATED by scripts/generate-procurement-register.mjs — do not edit by hand.
// Source: goods_procurement_entities in the ACT infrastructure Supabase, deduped by ABN.
// Regenerate with: node scripts/generate-procurement-register.mjs
//
// Read ${rows.length} rows, kept ${entities.length} distinct entities. The source table is an
// entity x community cross-join, so its raw totals are inflated roughly nine-fold; these are the
// deduped figures and they are the only ones safe to print.

export interface ProcurementEntity {
  name: string;
  abn: string | null;
  /** grantscope id, ABN-keyed (AU-ABN-<abn>). */
  grantscopeId: string | null;
  entityType: string | null;
  buyerRole: string | null;
  communityControlled: boolean;
  govtContractCount: number;
  govtContractValue: number;
  procurementMethod: string | null;
  website: string | null;
}

export const PROCUREMENT_REGISTER: ProcurementEntity[] = [
${entities.map((e) => `  { name: '${esc(e.entity_name)}', abn: ${e.abn ? `'${esc(e.abn)}'` : 'null'}, grantscopeId: ${e.gs_id ? `'${esc(e.gs_id)}'` : 'null'}, entityType: ${e.entity_type ? `'${esc(e.entity_type)}'` : 'null'}, buyerRole: ${e.buyer_role ? `'${esc(e.buyer_role)}'` : 'null'}, communityControlled: ${!!e.is_community_controlled}, govtContractCount: ${e.govt_contract_count ?? 0}, govtContractValue: ${e.govt_contract_value ?? 0}, procurementMethod: ${e.procurement_method ? `'${esc(e.procurement_method)}'` : 'null'}, website: ${e.website ? `'${esc(e.website)}'` : 'null'} },`).join('\n')}
];

/**
 * The prospect set: community-controlled AND already holding a government contract. These are the
 * organisations that could sell a bed without a tender and have proven they can hold a contract.
 * There are ${both} of them, which is the real size of the opportunity — not the 4,562 rows.
 */
export const CAN_SELL_AND_HOLDS_CONTRACTS = PROCUREMENT_REGISTER.filter(
  (e) => e.communityControlled && e.govtContractCount > 0,
);

/** Figures as generated, so a guard can catch silent drift. */
export const PROCUREMENT_REGISTER_STATS = {
  sourceRows: ${rows.length},
  entities: ${entities.length},
  communityControlled: ${communityControlled},
  withContracts: ${withContracts},
  both: ${both},
  totalContractValue: ${totalValue},
} as const;
`;

  writeFileSync(OUT, body);
  console.log(`rows read        : ${rows.length}`);
  console.log(`entities written : ${entities.length}`);
  console.log(`  community-controlled : ${communityControlled}`);
  console.log(`  holding contracts    : ${withContracts}`);
  console.log(`  BOTH                 : ${both}`);
  console.log(`  contract value       : $${totalValue.toLocaleString()}`);
  console.log(`\nwrote ${OUT}`);
}

main().catch((e) => { console.error(e); process.exit(2); });
